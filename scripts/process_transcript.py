def ensure_max_length(text, max_len=450):
    """将长文本按句号/问号/感叹号拆分为不超过max_len字的小段"""
    if len(text) <= max_len:
        return [text]
    segments = []
    remaining = text.strip()
    while remaining:
        if len(remaining) <= max_len:
            segments.append(remaining)
            break
        chunk = remaining[:max_len]
        break_at = -1
        for c in ['\u3002', '\uff1f', '\uff01', '\uff1b']:  # 。？！；
            pos = chunk.rfind(c)
            if pos > break_at:
                break_at = pos
        if break_at > max_len * 0.3:
            segments.append(chunk[:break_at + 1].strip())
            remaining = remaining[break_at + 1:]
        else:
            # 找不到合适断点，在最后位置截断
            segments.append(chunk.strip())
            remaining = remaining[max_len:]
    return segments


def split_long_text(text):
    """将长文本按主题转折拆分为多个段落（主要分段逻辑）
    
    仅按 TOPIC_SPLIT_MARKERS 中的重大主题转折拆分，保持段落连贯。
    细粒度子标题 TOPIC_TRANSITIONS 不用于拆分文字，只用于在段落前插入标题。
    """
    import re as _re
    text = text.replace("\n", "").replace("\r", "")
    
    # 只按重大主题标记拆分，不按子标题关键词拆分
    markers_sorted = sorted(set(TOPIC_SPLIT_MARKERS), key=lambda m: -len(m))
    
    pattern = "(" + "|".join(_re.escape(m) for m in markers_sorted) + ")"
    parts = _re.split(pattern, text)
    segments = []
    i = 0
    while i < len(parts):
        p = parts[i].strip()
        if not p:
            i += 1
            continue
        if p in set(TOPIC_SPLIT_MARKERS):
            seg = p
            if i + 1 < len(parts):
                seg += parts[i + 1].strip()
                i += 2
            else:
                i += 1
            segments.append(seg)
        else:
            if i + 1 < len(parts) and parts[i + 1].strip() in set(TOPIC_SPLIT_MARKERS):
                segments.append(p)
                i += 1
            else:
                segments.append(p)
                i += 1
    if not segments:
        segments = [text]
    return segments

