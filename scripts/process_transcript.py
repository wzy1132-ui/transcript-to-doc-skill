def add_marked_text_runs(paragraph, text, font_name, force_gray_strike=False):
    """添加正文 run，并将口头语气词或指定片段标为灰色删除线。"""
    frags = [(text, force_gray_strike)]
    if not force_gray_strike:
        for (mg,) in MARK_FRAGMENTS_GRAY:
            new_frags = []
            for seg, is_marked in frags:
                if is_marked:
                    new_frags.append((seg, is_marked))
                    continue
                while mg in seg:
                    idx = seg.index(mg)
                    if idx > 0:
                        new_frags.append((seg[:idx], False))
                    new_frags.append((mg, True))
                    seg = seg[idx + len(mg):]
                if seg:
                    new_frags.append((seg, False))
            frags = new_frags

    for frag_text, is_marked in frags:
        if not frag_text:
            continue
        if is_marked:
            run = paragraph.add_run(frag_text)
            apply_run_font(run, font_name, gray_strike=True)
            continue
        pos = 0
        for m in INLINE_FILLER_RE.finditer(frag_text):
            if m.start() > pos:
                run = paragraph.add_run(frag_text[pos:m.start()])
                apply_run_font(run, font_name)
            run = paragraph.add_run(m.group(0))
            apply_run_font(run, font_name, gray_strike=True)
            pos = m.end()
        if pos < len(frag_text):
            run = paragraph.add_run(frag_text[pos:])
            apply_run_font(run, font_name)

